package com.crm.core.entity.enums;

/**
 * Базовые роли сотрудников школы (MVP). Конструктор ролей и точечные разрешения — после пилота.
 * В {@code @PreAuthorize} используются как {@code hasRole('ADMIN')} и т. п.
 */
public enum StaffRole {
    ADMIN,    // Администратор школы: сотрудники, настройки, расписание, всё остальное
    MANAGER,  // Менеджер: лиды, клиенты, задачи
    TEACHER,  // Преподаватель: только своё расписание, группы и ученики; без финансов
    FINANCE;  // Финансовый сотрудник: счета, платежи, задолженность

    public String authority() {
        return "ROLE_" + name();
    }
}
